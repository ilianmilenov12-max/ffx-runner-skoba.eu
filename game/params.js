// --- преследвачът -----------------------------------------------------
// "BehaviorScript 35 - PallaDaBowlingCPU2". Усилванията там са записани
// умножени по масата; при импулс = маса × скорост тя се съкращава, затова
// тук стоят вече поделени.

// Пределната скорост не е maxSpeed, а maxSpeed·(acc·grip)/(acc·grip+drag).
// По оригиналните числа излиза: играч 57.2, гонител 56.2, засада 80.5,
// улична 46.2 фута в секунда. Тоест гонителят е с една десета по-бавен от
// играча, а уличната — с цяла четвърт: на права отсечка и двете изостават
// завинаги и играта се разпада на безкрайно бягство.
//
// В оригинала това не личи, защото колите са три и се сменят чрез
// появяването зад камерата. Тук вдигаме двете бавни толкова, колкото да
// могат да настигат: гонителят до 65.6, уличната до 64.6.
