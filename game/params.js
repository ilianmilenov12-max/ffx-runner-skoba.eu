  maxSpeed: 175.0,          // pMaxSpeed (в оригинала 150)
  accGain: 0.04,            // pAccGain / pMass
  decGain: 0.04,            // pDecGain / pMass
  brakeGain: 0.1,           // pBrakeGain / pMass
  turnGain: 0.5,            // pTurnGain / pMass — по-остър волан от този на играча
  reTurnGain: 0.5,          // pReTurnGain / pMass
